#!/usr/bin/env python3
"""Build deterministic gzip + a committed WEB2 image for two allocated sectors."""
import gzip
import hashlib
import io
import json
import struct
import zlib
from pathlib import Path

root = Path(__file__).resolve().parents[1]
html = (root / 'assets/index.html').read_bytes()
compressed = io.BytesIO()
with gzip.GzipFile(fileobj=compressed, mode='wb', filename='', mtime=0, compresslevel=9) as stream:
    stream.write(html)
payload = compressed.getvalue()
header = struct.pack('<4sBBHI3sB', b'WEB2', 1, 1, len(payload), zlib.crc32(payload), b'\0'*3, 0xa5)
blob = header + payload
if len(blob) > 8192:
    raise SystemExit(f'Compressed UI needs {len(blob)} bytes; two-sector limit is 8192')
out = root / 'build/web-assets.bin'
out.parent.mkdir(exist_ok=True)
out.write_bytes(blob)
(root / 'build/web-assets.gz').write_bytes(payload)
(root / 'build/web_assets_data.h').write_text(
    '/* Generated by tools/build_assets.py; stored in program flash for installation. */\n'
    f'#define WEB_IMAGE_SIZE {len(blob)}u\n#define WEB_GZIP_LENGTH {len(payload)}u\n'
    'static const uint8_t web_asset_image[WEB_IMAGE_SIZE] = {\n' +
    '\n'.join('    '+','.join(f'0x{x:02x}' for x in blob[i:i+16])+',' for i in range(0,len(blob),16)) + '\n};\n')
out.with_suffix('.json').write_text(json.dumps({
    'format':'WEB2','version':1,'encoding':'gzip','address':'0x51000',
    'bytes':len(blob),'gzip_bytes':len(payload),'html_bytes':len(html),
    'sha256':hashlib.sha256(blob).hexdigest(),'gzip_crc32':f'{zlib.crc32(payload):08x}'
},indent=2)+'\n')
print(f'UI: {len(html)} bytes HTML → {len(payload)} bytes gzip; image {len(blob)}/8192 bytes')
