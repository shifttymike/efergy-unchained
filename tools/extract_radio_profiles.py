#!/usr/bin/env python3
"""Extract literal RFM register writes from the selected original firmware.
This is intentionally limited to the two straight-line setup branches.
"""
import argparse
import hashlib
import re
import subprocess
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("hex", type=Path)
parser.add_argument("output", type=Path)
args = parser.parse_args()
text = subprocess.check_output(["gpdasm", "-p18f67j60", str(args.hex)], text=True)
profiles = []
for start, end in ((0xf21a, 0xf36e), (0xf370, 0xf4ca)):
    working = None
    ram = {}
    writes = []
    for line in text.splitlines():
        match = re.match(r"([0-9a-f]{6}):\s+[0-9a-f]{4}\s+(.+)", line)
        if not match or not start <= int(match[1], 16) < end:
            continue
        instruction = match[2]
        literal = re.match(r"movlw\s+0x([0-9a-f]+)", instruction)
        store = re.match(r"movwf\s+0x(88|89),", instruction)
        clear = re.match(r"clrf\s+0x(88|89),", instruction)
        if literal:
            working = int(literal[1], 16)
        elif store:
            assert working is not None
            ram[int(store[1],16)] = working
        elif clear:
            ram[int(clear[1],16)] = 0
        elif "rcall" in instruction and "0x00f572" in instruction:
            writes.append((ram[0x88],ram[0x89]))
    assert len(writes) >= 20
    profiles.append(writes)
lines = ["/* Generated by tools/extract_radio_profiles.py; do not hand edit.",
         " * Original HEX SHA256: " + hashlib.sha256(args.hex.read_bytes()).hexdigest(),
         " */", "#include <stdint.h>", "typedef struct { uint8_t reg, value; } radio_register_t;"]
for name, writes in zip(("a", "b"),profiles):
    lines.append("static const radio_register_t profile_" + name + "[] = {")
    lines.extend("    {0x%02x,0x%02x}," % pair for pair in writes)
    lines.append("};")
args.output.write_text("\n".join(lines)+"\n")
print("extracted", *(len(p) for p in profiles), "register writes")
